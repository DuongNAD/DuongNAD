class TestCssSpecificityAndVariableInheritance(unittest.TestCase):
    """
    Stress-tests CSS rule definitions, variable binding, keyframe animations,
    and Living Systems emerald/teal palette harmony.
    """

    def setUp(self):
        self.header_path = REPO_ROOT / "assets" / "header.svg"
        self.footer_path = REPO_ROOT / "assets" / "footer.svg"
        self.snake_dark_path = REPO_ROOT / "assets" / "github-contribution-grid-snake-dark.svg"

    def test_snake_dark_css_variable_integrity(self):
        """
        Verify CSS variables in github-contribution-grid-snake-dark.svg:
        - All variables referenced via var(--name) must be explicitly defined in :root.
        - Exactly 0 undefined variable fallbacks.
        - Zero cyber-blue/neon hex literals in the stylesheet.
        """
        content = self.snake_dark_path.read_text(encoding="utf-8")
        style_match = re.search(r"<style>(.*?)</style>", content, re.DOTALL)
        self.assertIsNotNone(style_match, "Style tag missing in snake dark asset")
        css_text = style_match.group(1)

        # 1. Extract :root block
        root_match = re.search(r':root\s*\{([^}]+)\}', css_text)
        self.assertIsNotNone(root_match, ":root block missing in snake dark CSS")
        root_body = root_match.group(1)

        # Parse declared variables
        declared_vars = {}
        for decl in root_body.split(";"):
            decl = decl.strip()
            if decl and ":" in decl:
                var_name, var_val = decl.split(":", 1)
                declared_vars[var_name.strip()] = var_val.strip()

        # Check required snake variables
        required_vars = ["--cb", "--cs", "--ce", "--c0", "--c1", "--c2", "--c3", "--c4"]
        for req in required_vars:
            self.assertIn(req, declared_vars, f"Required CSS variable '{req}' missing from :root")

        # 2. Extract all var(--name) usages
        var_usages = set(re.findall(r'var\((--[a-zA-Z0-9_\-]+)\)', css_text))
        for usage in var_usages:
            self.assertIn(
                usage, declared_vars,
                f"Variable '{usage}' used in animation or cell rules but never defined in :root!"
            )

        # 3. Check palette values in :root: must be living systems emeralds/slate
        for var_name, color_val in declared_vars.items():
            clean_hex = color_val.lstrip("#").upper()
            if len(clean_hex) == 8: # e.g. 1b1f230a with alpha
                clean_hex = clean_hex[:6]
            self.assertNotIn(
                clean_hex, FORBIDDEN_CYAN_BLUE_HEXES,
                f"Forbidden sci-fi blue/neon hex '{color_val}' found in {var_name}"
            )

        # 4. Verify snake head is emerald #10B981
        self.assertEqual(
            declared_vars.get("--cs", "").upper(), "#10B981",
            f"Snake head --cs must be emerald #10B981, found {declared_vars.get('--cs')}"
        )

    def test_css_selector_specificity_and_scoping(self):
        """
        Verify CSS in header.svg and footer.svg does NOT use universal selectors
        or unbounded HTML element tags that could break when embedded in SVGs.
        """
        for target in [self.header_path, self.footer_path]:
            content = target.read_text(encoding="utf-8")
            style_match = re.search(r"<style>(.*?)</style>", content, re.DOTALL)
            if not style_match:
                continue
            css_text = style_match.group(1)

            # Strip comments and @keyframes blocks to inspect rule selectors
            no_keyframes = re.sub(r'@keyframes[^{]+\{(?:[^{}]*\{[^{}]*\})*[\s\n]*\}', '', css_text, flags=re.DOTALL)
            rules = re.findall(r'([^{]+)\{([^}]+)\}', no_keyframes)

            for selector, body in rules:
                selector = selector.strip()
                self.assertNotIn("*", selector, f"Forbidden universal selector '*' in {target.name}: {selector}")
                # All custom styling should be class-based or keyframes
                self.assertTrue(
                    selector.startswith(".") or selector.startswith(":"),
                    f"Unscoped rule selector in {target.name}: '{selector}' (should be class-scoped e.g. '.title-text')"
                )

    def test_keyframes_timing_and_animations_stability(self):
        """Verify animation durations, easing curves, and keyframe intervals are valid."""
        for target in [self.header_path, self.footer_path]:
            content = target.read_text(encoding="utf-8")
            keyframes = re.findall(r'@keyframes\s+([a-zA-Z0-9_\-]+)\s*\{([^}]+)\}', content)
            self.assertGreater(len(keyframes), 0, f"{target.name} should define living systems micro-animations")

            for kf_name, kf_body in keyframes:
                stops = re.findall(r'(\d+)%', kf_body)
                self.assertIn("0", stops, f"Keyframe '{kf_name}' missing 0% stop")
                self.assertIn("100", stops, f"Keyframe '{kf_name}' missing 100% stop")


