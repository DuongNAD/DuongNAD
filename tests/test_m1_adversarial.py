class TestXmlNamespaceAndCharacterEncoding(unittest.TestCase):
    """
    Validates XML namespace declarations, multi-parser consensus (DOM, SAX, ET),
    and character encoding integrity (UTF-8, NFC diacritics, XML entity escaping).
    """

    def setUp(self):
        self.header_path = REPO_ROOT / "assets" / "header.svg"
        self.footer_path = REPO_ROOT / "assets" / "footer.svg"
        self.snake_dark_path = REPO_ROOT / "assets" / "github-contribution-grid-snake-dark.svg"
        self.targets = [self.header_path, self.footer_path, self.snake_dark_path]

    def test_multi_parser_consensus(self):
        """
        Verify all target SVGs parse identically across 3 independent XML parsers:
        1. xml.etree.ElementTree (C-accelerated tree builder)
        2. xml.dom.minidom (W3C DOM Level 2 parser)
        3. xml.sax (Streaming event parser with namespace validation)
        """
        class StrictSaxHandler(xml.sax.handler.ContentHandler):
            def __init__(self):
                super().__init__()
                self.element_count = 0
                self.has_svg_root = False

            def startElementNS(self, name, qname, attrs):
                uri, localname = name
                if self.element_count == 0:
                    if uri == "http://www.w3.org/2000/svg" and localname == "svg":
                        self.has_svg_root = True
                self.element_count += 1

        for target in self.targets:
            # 1. ElementTree
            et_root = ET.parse(target).getroot()
            self.assertEqual(et_root.tag, "{http://www.w3.org/2000/svg}svg")

            # 2. Minidom
            dom = xml.dom.minidom.parse(str(target))
            self.assertEqual(dom.documentElement.tagName, "svg")
            self.assertEqual(dom.documentElement.getAttribute("xmlns"), "http://www.w3.org/2000/svg")

            # 3. SAX with Namespace feature
            parser = xml.sax.make_parser()
            parser.setFeature(xml.sax.handler.feature_namespaces, True)
            handler = StrictSaxHandler()
            parser.setContentHandler(handler)
            with open(target, "rb") as f:
                parser.parse(f)
            self.assertTrue(handler.has_svg_root, f"{target.name} SAX parser failed to find SVG root in SVG namespace")
            self.assertGreater(handler.element_count, 1, f"{target.name} element count too low")

    def test_utf8_clean_bytes_and_diacritics_normalization(self):
        """
        Verify strict UTF-8 decoding without replacement characters or BOM.
        Verify Unicode NFC canonical decomposition/composition on Vietnamese diacritics.
        """
        for target in self.targets:
            raw = target.read_bytes()

            # Disallow UTF-8 BOM (\xef\xbb\xbf) which can break some strict SVG processors
            self.assertFalse(raw.startswith(b"\xef\xbb\xbf"), f"{target.name} has unexpected UTF-8 BOM header")

            # Decode strictly as UTF-8
            text = raw.decode("utf-8")
            self.assertNotIn("\ufffd", text, f"{target.name} contains Unicode REPLACEMENT CHARACTER (U+FFFD)")

            # Check normalization
            nfc_text = unicodedata.normalize("NFC", text)
            self.assertEqual(text, nfc_text, f"{target.name} text should be canonical Unicode NFC form")

    def test_vietnamese_diacritics_and_special_symbols(self):
        """Verify candidate's name diacritics ('NGUYỄN ANH DƯƠNG') and symbols are preserved."""
        header_text = self.header_path.read_text(encoding="utf-8")
        self.assertIn("NGUYỄN ANH DƯƠNG", header_text, "Candidate name with diacritics missing in header.svg")
        self.assertIn("✦", header_text, "Star symbol '✦' missing in header badge")
        self.assertIn("·", header_text, "Middle dot symbol '·' missing in header meta")

        # Explicit codepoint check for Vietnamese diacritics
        name = "NGUYỄN ANH DƯƠNG"
        self.assertIn("\u1ec4", name, "Ễ (U+1EC4) must be present")
        self.assertIn("\u01af", name, "Ư (U+01AF) must be present")
        self.assertIn("\u01a0", name, "Ơ (U+01A0) must be present")

        footer_text = self.footer_path.read_text(encoding="utf-8")
        self.assertIn("NGUYEN ANH DUONG (DuongNAD)", footer_text, "Signature missing in footer.svg")
        self.assertIn("·", footer_text, "Middle dot symbol '·' missing in footer.svg")

    def test_xml_entity_escaping_soundness(self):
        """
        Verify all literal ampersands in markup, attributes, and text nodes are properly escaped as &amp;.
        Ignores XML comments where ampersands are valid non-markup characters.
        """
        for target in self.targets:
            content = target.read_text(encoding="utf-8")
            # Strip comments first
            no_comments = re.sub(r'<!--.*?-->', '', content, flags=re.DOTALL)
            raw_amp_pattern = r'&(?!(amp|lt|gt|quot|apos|#\d+|#x[0-9a-fA-F]+);)'
            raw_amps = re.findall(raw_amp_pattern, no_comments)
            self.assertEqual(
                len(raw_amps), 0,
                f"Found {len(raw_amps)} unescaped ampersand(s) outside comments in {target.name}"
            )


